"""Inverse cellular automaton — planting the flag on the framing (2026-07-22).

The framing says the method's home is the intersection of: (1) a BLACK-BOX,
non-differentiable objective; (2) a CONTINUOUS, structured solution manifold;
(3) a FAMILY of related instances so the learnable prior transfers. A single
problem where all three hold and where gradient descent is genuinely LOCKED
OUT (not just beaten): inverse design through a thresholded cellular
automaton.

Forward map (non-differentiable): a majority-vote CA. Each step, a cell turns
on iff >=5 of its 3x3 neighbourhood (including itself) are on. The hard
threshold has zero gradient a.e., so you CANNOT backprop a target-match loss
to the initial field — gradient descent cannot solve this at all.

Problem: find a continuous initial field whose K-step CA output matches a
target pattern. Targets are generated by running the CA forward from
structured (blob) seeds, so a solution provably exists and the family shares
generation structure — the decoder can learn the manifold of good initial
fields and transfer it to held-out targets.

We run the same cold-vs-warm transfer test that confirmed the thesis on
images, now on a problem gradients can't touch.
"""
from __future__ import annotations

import argparse

import numpy as np
import torch

from benchmarks.experimental_distill_loop import Config, run

H = W = 32
K = 4


def make_ca_transform(device):
    kernel = torch.ones(1, 1, 3, 3, device=device)

    def transform(flat):                 # (n, H*W) in [0,1] -> (n, H*W) {0,1}
        s = (flat.reshape(-1, 1, H, W) > 0.5).float()
        for _ in range(K):
            s = (torch.conv2d(s, kernel, padding=1) >= 5).float()
        return s.reshape(len(flat), -1)
    return transform


def make_target(rng, transform, device):
    """A target = the CA run forward from a random blob seed (solution exists)."""
    yy, xx = np.mgrid[0:H, 0:W]
    field = np.zeros((H, W))
    for _ in range(int(rng.integers(3, 6))):
        cy, cx = rng.uniform(5, H - 5, 2)
        sd = rng.uniform(3.0, 6.0)
        field += np.exp(-((yy - cy) ** 2 + (xx - cx) ** 2) / (2 * sd * sd))
    seed = (field > 0.5 * field.max()).astype(np.float32)
    tgt = transform(torch.as_tensor(seed.reshape(1, -1), device=device))
    return tgt.reshape(H, W).cpu().numpy()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--train-epochs", type=int, default=1500)
    parser.add_argument("--test-epochs", type=int, default=800)
    parser.add_argument("--seed", type=int, default=3)
    parser.add_argument("--smoke", action="store_true",
                        help="quick single-target solvability check only")
    args = parser.parse_args()

    device = "mps" if torch.backends.mps.is_available() else "cpu"
    rng = np.random.default_rng(args.seed)
    transform = make_ca_transform(device)
    shape = (H, W)

    if args.smoke:
        tgt = make_target(rng, transform, device)
        cfg = Config(epochs=300, children=12, patch=1024)
        mean, per = run([tgt, make_target(rng, transform, device)], shape, cfg,
                        seed=args.seed, device=device, transform=transform,
                        log=100)
        print(f"smoke: solvable? mean error removed {mean:.1f}% "
              f"(gradient descent: 0% — objective non-differentiable)")
        return

    train = [make_target(rng, transform, device) for _ in range(16)]
    held = [make_target(rng, transform, device) for _ in range(8)]

    print(f"WARMING decoder on 16 inverse-CA targets "
          f"({args.train_epochs} epochs)...", flush=True)
    _, _, gen, _ = run(train, shape, Config(epochs=args.train_epochs),
                       seed=args.seed, device=device, transform=transform,
                       return_full=True, log=max(1, args.train_epochs // 4))
    warm_state = {k: v.clone() for k, v in gen.net.state_dict().items()}

    print("\n=== held-out inverse-CA: cold vs warm ===", flush=True)
    traces = {}
    for arm, init in (("cold", None), ("warm", warm_state)):
        _, _, _, trace = run(held, shape, Config(epochs=args.test_epochs),
                             seed=args.seed + 1, device=device,
                             init_state=init, transform=transform,
                             return_full=True)
        traces[arm] = dict(trace)
    print(f"  {'epoch':>6} {'cold MSE':>10} {'warm MSE':>10} {'warm/cold':>10}")
    for e in sorted(traces["cold"]):
        c, w = traces["cold"][e], traces["warm"][e]
        print(f"  {e:>6} {c:>10.5f} {w:>10.5f} {w / c:>10.2f}", flush=True)


if __name__ == "__main__":
    main()
